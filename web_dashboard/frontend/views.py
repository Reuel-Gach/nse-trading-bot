@login_required
def trade_journal(request):
    journal_entries = TradeJournal.objects.filter(user=request.user).order_by('-date_closed')
    
    total_trades = journal_entries.count()
    winning_trades = journal_entries.filter(pnl_value__gt=0).count()
    win_rate = (winning_trades / total_trades * 100) if total_trades > 0 else 0.0
    
    account, _ = Account.objects.get_or_create(user=request.user)
    
    context = {
        'entries': journal_entries,
        'total_trades': total_trades,
        'win_rate': win_rate,
        'total_realized': account.total_realized_profit,
    }
    return render(request, 'frontend/journal.html', context)

@login_required
def close_position(request, position_id):
    if request.method == 'POST':
        pos = get_object_or_404(PortfolioPosition, id=position_id, user=request.user)
        exit_price = float(request.POST.get('exit_price'))
        exit_reason = request.POST.get('exit_reason', 'Manual Exit')
        
        invested_val = pos.shares * pos.entry_price
        exit_val = pos.shares * exit_price
        pnl_val = exit_val - invested_val
        pnl_pct = (pnl_val / invested_val * 100) if invested_val > 0 else 0.0
        
        TradeJournal.objects.create(
            user=request.user,
            ticker=pos.ticker,
            shares=pos.shares,
            entry_price=pos.entry_price,
            exit_price=exit_price,
            pnl_value=pnl_val,
            pnl_percent=pnl_pct,
            exit_reason=exit_reason
        )
        
        account, _ = Account.objects.get_or_create(user=request.user)
        account.total_realized_profit += pnl_val
        account.save()
        
        pos.delete()
        messages.success(request, f"{pos.ticker} closed. Realized P&L: KES {pnl_val:.2f} logged to journal.")
    return redirect('dashboard')

