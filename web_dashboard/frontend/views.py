def get_latest_prices():
    """Reads the EOD CSV generated by the bot to get real-time prices."""
    csv_path = os.path.abspath(os.path.join(settings.BASE_DIR, "..", "data", "nse_historical_data.csv"))
    prices = {}
    if os.path.exists(csv_path):
        try:
            df = pd.read_csv(csv_path)
            latest = df.drop_duplicates(subset=['ticker'], keep='last')
            for _, row in latest.iterrows():
                prices[row['ticker']] = row['close']
        except Exception as e:
            print(f"Error reading market CSV: {e}")
    return prices

@login_required
def dashboard(request):
    account, _ = Account.objects.get_or_create(user=request.user)
    positions = PortfolioPosition.objects.filter(user=request.user).order_by('-date_added')
    latest_prices = get_latest_prices()
    
    portfolio_data = []
    total_invested = 0.0
    current_value = 0.0
    
    for pos in positions:
        current_price = latest_prices.get(pos.ticker, pos.entry_price)
        invested_val = pos.shares * pos.entry_price
        current_val = pos.shares * current_price
        pnl_val = current_val - invested_val
        pnl_pct = (pnl_val / invested_val * 100) if invested_val > 0 else 0.0
        
        if pos.status == 'OPEN':
            total_invested += invested_val
            current_value += current_val
            
        portfolio_data.append({
            'id': pos.id,
            'ticker': pos.ticker,
            'shares': pos.shares,
            'entry_price': pos.entry_price,
            'current_price': current_price,
            'current_stop_loss': pos.current_stop_loss,
            'invested_value': invested_val,
            'current_value': current_val,
            'pnl_value': pnl_val,
            'pnl_percent': pnl_pct,
            'status': pos.status
        })
        
    net_gain = current_value - total_invested
    net_gain_pct = (net_gain / total_invested * 100) if total_invested > 0 else 0.0

    context = {
        'portfolio': portfolio_data,
        'total_invested': total_invested,
        'current_value': current_value,
        'net_gain': net_gain,
        'net_gain_pct': net_gain_pct,
        'total_realized': account.total_realized_profit,
    }
    return render(request, 'frontend/dashboard.html', context)

@login_required
def add_position(request):
    """Executes trade logging, automatically consolidating with existing OPEN positions."""
    if request.method == 'POST':
        ticker = request.POST.get('ticker').upper()
        new_shares = int(request.POST.get('shares'))
        new_entry_price = float(request.POST.get('entry_price'))
        stop_loss = request.POST.get('stop_loss')
        status = request.POST.get('status', 'OPEN')
        
        parsed_stop_loss = float(stop_loss) if stop_loss else None

        existing_pos = PortfolioPosition.objects.filter(
            user=request.user, 
            ticker=ticker, 
            status='OPEN'
        ).first()

        if existing_pos and status == 'OPEN':
            old_shares = existing_pos.shares
            old_price = existing_pos.entry_price
            
            total_shares = old_shares + new_shares
            total_cost = (old_shares * old_price) + (new_shares * new_entry_price)
            new_avg_price = total_cost / total_shares if total_shares > 0 else new_entry_price
            
            existing_pos.shares = total_shares
            existing_pos.entry_price = new_avg_price
            if parsed_stop_loss:
                existing_pos.current_stop_loss = parsed_stop_loss
            existing_pos.save()
            
            messages.success(request, f"Consolidated {ticker}: Added {new_shares} units. New total: {total_shares} shares @ KES {new_avg_price:.2f}.")
        else:
            PortfolioPosition.objects.create(
                user=request.user,
                ticker=ticker,
                shares=new_shares,
                entry_price=new_entry_price,
                current_stop_loss=parsed_stop_loss,
                status=status
            )
            messages.success(request, f"Trade logged: {new_shares} units of {ticker}.")
            
    return redirect('dashboard')

@login_required
def edit_position(request, position_id):
    if request.method == 'POST':
        pos = get_object_or_404(PortfolioPosition, id=position_id, user=request.user)
        pos.ticker = request.POST.get('ticker').upper()
        pos.shares = int(request.POST.get('shares'))
        pos.entry_price = float(request.POST.get('entry_price'))
        
        stop_loss = request.POST.get('stop_loss')
        pos.current_stop_loss = float(stop_loss) if stop_loss else None
        pos.status = request.POST.get('status', 'OPEN')
        
        pos.save()
        messages.success(request, f"{pos.ticker} ledger updated.")
    return redirect('dashboard')

