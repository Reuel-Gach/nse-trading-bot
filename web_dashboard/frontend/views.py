@login_required
def dispatch_eod_manual(request):
    """Manually triggers and dispatches the EOD summary report from Control Room."""
    if request.method == 'POST':
        try:
            user_email = request.user.email or os.environ.get("GMAIL_RECIPIENT", "")
            username = request.user.username
            
            latest_prices = get_latest_prices()
            positions = PortfolioPosition.objects.filter(user=request.user, status='OPEN')
            open_pos_list = []
            total_equity = 0.0
            
            for p in positions:
                curr = latest_prices.get(p.ticker, p.entry_price)
                val = p.shares * curr
                total_equity += val
                open_pos_list.append({
                    'ticker': p.ticker,
                    'shares': p.shares,
                    'entry': p.entry_price,
                    'current': curr,
                    'pnl_val': val - (p.shares * p.entry_price)
                })
                
            account, _ = Account.objects.get_or_create(user=request.user)
            portfolio = {
                "total_equity": total_equity,
                "cash": 0.0,
                "realized_profit": account.total_realized_profit,
                "open_positions": open_pos_list
            }
            
            dispatch_eod_summary_report(
                recipient_email=user_email,
                username=username,
                portfolio=portfolio,
                all_signals=[],
                latest_prices=latest_prices
            )
            messages.success(request, "✅ EOD Closing Report successfully dispatched to your email!")
        except Exception as e:
            messages.error(request, f"❌ Failed to dispatch EOD report: {e}")
            
    return redirect('control_room')

@login_required
def clear_logs_manual(request):
    """Clears out runtime lock and log files from the logs directory."""
    if request.method == 'POST':
        try:
            logs_dir = os.path.abspath(os.path.join(settings.BASE_DIR, "..", "logs"))
            log_files = glob.glob(os.path.join(logs_dir, '*.txt')) + glob.glob(os.path.join(logs_dir, '*.json'))
            
            count = 0
            for f in log_files:
                if 'eod_sent' in f or 'sent_alerts' in f or 'cron' in f:
                    os.remove(f)
                    count += 1
                    
            messages.success(request, f"🧹 Successfully purged {count} runtime lock/log files.")
        except Exception as e:
            messages.error(request, f"❌ Error clearing logs: {e}")
            
    return redirect('control_room')

